-- 装备（官方通用口径）：装备区有四条槽位（开局设一次）
-- 牌上的数据就是描述里的值：武器的攻击范围（用的时候减掉默认 1，见 @基础/卡牌/武器牌.lua）、坐骑的距离修正（那是全部值）
-- 加成由牌自己的「进入区域」钩子写进属性、撤销挂在牌上（牌一离开装备区就自动撤），所以没有「卸下」

game:on('游戏-开始', function ()
    for _, player in ipairs(game.desk.players) do
        player:getZone('装备'):setSlots({ '武器', '防具', '进攻马', '防御马' })
    end
end)
